"""Stage / layer layout and per-writer access.

    root.usda            static: sublayers + /World skeleton + read-only environment reference
     |- unity_ops.usda   ONLY Unity writes: /World/Dynamic/Obstacles/*, /World/Dynamic/Goal
     '- isaac_state.usda ONLY Isaac writes: /World/AGVs/*, /World/Dynamic/Paths/*, /World/Dynamic/Fleet,
                         the physics scene, lights

Isaac sets its edit target to isaac_state.usda for the whole session, so nothing it authors
(robot references included) can land in Unity's layer or the root. Unity's layer is only ever
Reload()ed here, never edited.
"""

from __future__ import annotations

import os

import config as cfg

ROOT_TEMPLATE = """#usda 1.0
(
    defaultPrim = "World"
    doc = "AGV fleet live-sync root stage. Static: generated by Tools/agv_fleet/launch_agv_fleet.py."
    metersPerUnit = 1
    upAxis = "Z"
{timing}    subLayers = [
        @./unity_ops.usda@,
        @./isaac_state.usda@{look}
    ]
)

def Xform "World"
{{
    def Xform "Environment" (
        doc = "Read-only in both tools. Environment preset: {env_name}."
        prepend references = @{env}@
    )
    {{
        float3 xformOp:scale = ({scale}, {scale}, {scale})
        uniform token[] xformOpOrder = ["xformOp:scale"]
    }}

    def Scope "AGVs"
    {{
    }}

    def Scope "Dynamic"
    {{
        def Scope "Paths"
        {{
        }}

        def Scope "Obstacles"
        {{
        }}
    }}
}}
"""

EMPTY_UNITY_LAYER = """#usda 1.0
(
    doc = "Written only by Unity (AGV operator front end). Placeholder created by Isaac on first run."
)
"""


def layer_relative(path: str) -> str:
    """Asset path as written into layers in UsdSync/AGVFleet: relative ("./../../...") when the file
    lives inside the project/package folder, so a copied package works from any location; absolute
    otherwise (e.g. the Isaac asset pack)."""
    p = os.path.abspath(path)
    root = os.path.abspath(str(cfg.PROJECT_ROOT))
    if os.path.splitdrive(p)[0].lower() == os.path.splitdrive(root)[0].lower() and \
            os.path.commonpath([p.lower(), root.lower()]) == root.lower():
        return "./" + os.path.relpath(p, str(cfg.STAGE_DIR)).replace("\\", "/")
    return p.replace("\\", "/")


def write_root_layer(look_layer: str | None = None, time_range: tuple | None = None):
    """(Re)write the static root layer for the active environment preset. Idempotent.
    The environment file's metersPerUnit is compensated by a scale on /World/Environment
    (references do not convert units by themselves). time_range = (start, end, timeCodesPerSecond)
    of the environment's own animation: a reference does not carry its layer's time code range, so
    without it Isaac's timeline would sit at frame 0 and never play the environment animation."""
    os.makedirs(cfg.STAGE_DIR, exist_ok=True)
    env = layer_relative(cfg.ENV_USD)
    look = f",\n        @./{os.path.basename(look_layer)}@" if look_layer else ""
    timing = ""
    if time_range:
        start, end, tcps = time_range
        timing = (f"    startTimeCode = {start:g}\n    endTimeCode = {end:g}\n"
                  f"    timeCodesPerSecond = {tcps:g}\n    framesPerSecond = {tcps:g}\n")
    text = ROOT_TEMPLATE.format(env=env, env_name=cfg.ENV, scale=f"{cfg.ENV_SCALE:g}", look=look, timing=timing)
    path = str(cfg.ROOT_LAYER)
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    if not os.path.exists(cfg.UNITY_LAYER):
        # Bootstrap only: an empty layer so the sublayer resolves before Unity has ever run.
        with open(cfg.UNITY_LAYER, "w", encoding="utf-8", newline="\n") as f:
            f.write(EMPTY_UNITY_LAYER)


def reset_isaac_layer():
    """Isaac's layer is session state: start every launch from an empty layer (pxr needed)."""
    from pxr import Sdf

    path = str(cfg.ISAAC_LAYER)
    layer = Sdf.Layer.FindOrOpen(path) if os.path.exists(path) else Sdf.Layer.CreateNew(path)
    layer.Clear()
    layer.comment = "Written only by Isaac Sim (AGV fleet sim). Checkpointed about once a second."
    layer.Save()
    return layer


class IsaacStateWriter:
    """Fast per-frame writes into isaac_state.usda via Sdf specs inside one ChangeBlock."""

    def __init__(self, stage, layer):
        from pxr import Sdf

        self._Sdf = Sdf
        self.stage = stage
        self.layer = layer
        self._specs: dict[tuple[str, str], object] = {}

    def _attr(self, prim_path: str, name: str, type_name):
        key = (prim_path, name)
        spec = self._specs.get(key)
        if spec is None:
            Sdf = self._Sdf
            prim_spec = Sdf.CreatePrimInLayer(self.layer, prim_path)
            spec = prim_spec.attributes.get(name)
            if spec is None:
                spec = Sdf.AttributeSpec(prim_spec, name, type_name, Sdf.VariabilityVarying, True)
            self._specs[key] = spec
        return spec

    def write_agvs(self, rows: list[dict]):
        """rows: dicts with id, pos(x,y,z), yaw, wheels(l,r), nav, task, sim_t, wall_ms."""
        from pxr import Gf, Sdf

        with Sdf.ChangeBlock():
            for r in rows:
                p = f"/World/AGVs/{r['id']}"
                self._attr(p, "agv:position", Sdf.ValueTypeNames.Double3).default = Gf.Vec3d(*r["pos"])
                self._attr(p, "agv:yaw", Sdf.ValueTypeNames.Double).default = float(r["yaw"])
                self._attr(p, "agv:wheelAngles", Sdf.ValueTypeNames.Double2).default = Gf.Vec2d(*r["wheels"])
                self._attr(p, "agv:navState", Sdf.ValueTypeNames.String).default = r["nav"]
                self._attr(p, "agv:task", Sdf.ValueTypeNames.String).default = r["task"]
                self._attr(p, "agv:simTime", Sdf.ValueTypeNames.Double).default = float(r["sim_t"])
                self._attr(p, "agv:wallMs", Sdf.ValueTypeNames.Double).default = float(r["wall_ms"])

    def write_path(self, agv_id: str, pts_xy: list, color):
        """BasisCurves /World/Dynamic/Paths/<agv> (linear), z slightly above the floor."""
        from pxr import Gf, Sdf, UsdGeom, Vt

        path = f"/World/Dynamic/Paths/{agv_id}"
        curve = UsdGeom.BasisCurves(self.stage.GetPrimAtPath(path))
        if not curve:
            curve = UsdGeom.BasisCurves.Define(self.stage, path)
            curve.CreateTypeAttr(UsdGeom.Tokens.linear)
            curve.CreateWrapAttr(UsdGeom.Tokens.nonperiodic)
            curve.CreateDisplayColorAttr(Vt.Vec3fArray([Gf.Vec3f(*color)]))
            curve.CreateWidthsAttr(Vt.FloatArray([0.06]))
            curve.SetWidthsInterpolation(UsdGeom.Tokens.constant)
        pts = [Gf.Vec3f(float(x), float(y), 0.03) for x, y in pts_xy]
        if len(pts) < 2:
            pts = []
        with Sdf.ChangeBlock():
            curve.GetPointsAttr().Set(Vt.Vec3fArray(pts))
            curve.GetCurveVertexCountsAttr().Set(Vt.IntArray([len(pts)] if pts else []))

    def write_fleet(self, assignments: dict, queue: list):
        from pxr import Sdf

        p = "/World/Dynamic/Fleet"
        with Sdf.ChangeBlock():
            prim_spec = Sdf.CreatePrimInLayer(self.layer, p)
            prim_spec.specifier = Sdf.SpecifierDef
            prim_spec.typeName = "Scope"
            self._attr(p, "fleet:assignments", Sdf.ValueTypeNames.StringArray).default = [
                f"{k}={v}" for k, v in assignments.items()
            ]
            self._attr(p, "fleet:queue", Sdf.ValueTypeNames.StringArray).default = list(queue)

    def save(self) -> bool:
        """Checkpoint the layer to disk. On Windows the rename over the old file fails while another
        process has it open (e.g. Unity importing the stage); that only skips this checkpoint -- the
        live state never depends on the file -- so log it once per streak and try again next time."""
        from pxr import Tf

        try:
            self.layer.Save()
        except Tf.ErrorException as e:
            if not getattr(self, "_save_failing", False):
                first = str(e).strip().splitlines()
                print(f"[agv_fleet] isaac layer checkpoint skipped (file busy?): {first[0] if first else e}", flush=True)
            self._save_failing = True
            return False
        if getattr(self, "_save_failing", False):
            print("[agv_fleet] isaac layer checkpoint saved again", flush=True)
        self._save_failing = False
        return True


class UnityLayerReader:
    """Detects changes to unity_ops.usda (TCP notice or mtime poll), reloads it, and reads the
    composed stage. Never writes."""

    def __init__(self, stage):
        from pxr import Sdf

        self.stage = stage
        self.layer = Sdf.Layer.FindOrOpen(str(cfg.UNITY_LAYER))
        self._mtime = self._stat()
        self.rev = -1

    def _stat(self) -> float:
        try:
            return os.stat(cfg.UNITY_LAYER).st_mtime_ns
        except OSError:
            return 0

    def changed_on_disk(self) -> bool:
        return self._stat() != self._mtime

    def reload(self) -> bool:
        self._mtime = self._stat()
        try:
            return self.layer.Reload(force=True)
        except Exception as e:  # a half-written file is retried on the next poll
            print(f"[agv_fleet] unity layer reload failed: {e}")
            self._mtime = 0
            return False

    def read_obstacles(self) -> dict:
        """name -> {corners:[(x,y)*4], z:(lo,hi), created_ms} from the composed stage."""
        from pxr import Gf, Usd, UsdGeom

        out = {}
        parent = self.stage.GetPrimAtPath("/World/Dynamic/Obstacles")
        if not parent:
            return out
        for prim in parent.GetChildren():
            if not prim.IsActive() or not prim.IsA(UsdGeom.Gprim):
                continue
            xf = UsdGeom.Xformable(prim).ComputeLocalToWorldTransform(Usd.TimeCode.Default())
            if prim.IsA(UsdGeom.Cube):
                h = UsdGeom.Cube(prim).GetSizeAttr().Get() * 0.5
                lo, hi = Gf.Vec3d(-h, -h, -h), Gf.Vec3d(h, h, h)
            else:
                rng = UsdGeom.Boundable(prim).ComputeExtent(Usd.TimeCode.Default()) if prim.IsA(UsdGeom.Boundable) else None
                if not rng:
                    continue
                lo, hi = Gf.Vec3d(rng[0]), Gf.Vec3d(rng[1])
            corners3 = [xf.Transform(Gf.Vec3d(x, y, z)) for x in (lo[0], hi[0]) for y in (lo[1], hi[1]) for z in (lo[2], hi[2])]
            zs = [c[2] for c in corners3]
            bottom = [xf.Transform(Gf.Vec3d(x, y, lo[2])) for x, y in ((lo[0], lo[1]), (hi[0], lo[1]), (hi[0], hi[1]), (lo[0], hi[1]))]
            attr = prim.GetAttribute("unity:createdWallMs")
            out[prim.GetName()] = {
                "corners": [(c[0], c[1]) for c in bottom],
                "z": (min(zs), max(zs)),
                "created_ms": attr.Get() if attr and attr.HasValue() else None,
            }
        return out

    def read_goal(self):
        """-> dict(seq, x, y, target, created_ms) or None."""
        from pxr import Usd, UsdGeom

        prim = self.stage.GetPrimAtPath("/World/Dynamic/Goal")
        if not prim or not prim.IsActive():
            return None
        seq = prim.GetAttribute("fleet:goalSeq")
        if not seq or not seq.HasValue():
            return None
        t = UsdGeom.Xformable(prim).ComputeLocalToWorldTransform(Usd.TimeCode.Default()).ExtractTranslation()
        tgt = prim.GetAttribute("fleet:targetAgv")
        created = prim.GetAttribute("unity:createdWallMs")
        return {
            "seq": int(seq.Get()),
            "x": float(t[0]),
            "y": float(t[1]),
            "target": (tgt.Get() or "") if tgt and tgt.HasValue() else "",
            "created_ms": created.Get() if created and created.HasValue() else None,
        }

    def read_reset_seq(self) -> int:
        prim = self.stage.GetPrimAtPath("/World/Dynamic/Obstacles")
        a = prim.GetAttribute("unity:resetSeq") if prim else None
        return int(a.Get()) if a and a.HasValue() else 0

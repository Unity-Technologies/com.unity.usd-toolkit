"""Environment animation for Unity: a frozen-frame layer + the keyframes, from the environment's time samples.

The Explorer Factory carries an animated welding cell (car body on a sledge, parts picked from a rack,
KUKA arms) as USD time samples. Isaac plays the stage timeline, so it shows that animation; Unity's
usd-toolkit importer reads every attribute at UsdTimeCode.Default(), which sees only default values,
so it imported the cell in its unrelated rest pose (car ~10 m off, rack parts elsewhere).

This module writes, once per environment (derived data, like env_look_<env>.usda):

    env_anim.usda    over every animated prim: xformOp / visibility DEFAULT values = the value at the
                     bake frame (the stage's start time code: what Isaac shows when play() starts).
                     Visibility that is invisible at the bake frame but visible later is authored
                     "inherited", so the importer still creates those meshes; Unity hides them from
                     the keyframes.
    root_unity.usda  Unity's entry point: sublayers env_anim.usda (stronger) over root.usda.
                     Isaac never opens it -- in Isaac a stronger default would override the time
                     samples and freeze its animation.
    env_anim.json    the keyframes for Unity to play the animation in step with Isaac's timeline
                     (the current time code arrives with every hub "state" message as anim_tc):
                     per animated prim the USD local matrix at each authored key, per visibility
                     attribute its (time, visible) steps. Paths are relative to the environment's
                     default prim (= /World/Environment in the root stage).
"""

from __future__ import annotations

import json
import os
import time

import config as cfg

LAYER_NAME = "env_anim.usda"
JSON_NAME = "env_anim.json"
UNITY_ROOT_NAME = "root_unity.usda"
VERSION = "v2"   # v2: de-instancing for the importer

UNITY_ROOT_TEMPLATE = """#usda 1.0
(
    defaultPrim = "World"
    doc = "Unity's entry point (generated by Tools/agv_fleet/anim_layer.py). root.usda plus the environment animation frozen at its start frame, because Unity's importer reads default values only. Isaac opens root.usda, never this."
    metersPerUnit = 1
    upAxis = "Z"
    subLayers = [
        @./{anim}@,
        @./root.usda@
    ]
)
"""


def _stamp() -> str:
    from .layers import layer_relative

    size = os.path.getsize(cfg.ENV_USD) if os.path.exists(cfg.ENV_USD) else 0
    return f"{cfg.ENV}|{layer_relative(cfg.ENV_USD)}|{size}|{VERSION}"


def _up_to_date(stamp: str) -> bool:
    jpath = cfg.STAGE_DIR / JSON_NAME
    if not (jpath.exists() and (cfg.STAGE_DIR / LAYER_NAME).exists() and (cfg.STAGE_DIR / UNITY_ROOT_NAME).exists()):
        return False
    try:
        with open(jpath, encoding="utf-8") as f:
            head = f.read(512)
        return f'"stamp": {json.dumps(stamp)}' in head
    except OSError:
        return False


def env_time_range() -> tuple | None:
    """(start, end, timeCodesPerSecond) authored on the environment file, or None (not animated).
    Read from the layer's metadata only (cheap: no stage composition)."""
    from pxr import Sdf

    layer = Sdf.Layer.FindOrOpen(cfg.ENV_USD)
    if not layer or not (layer.HasStartTimeCode() and layer.HasEndTimeCode()) or layer.endTimeCode <= layer.startTimeCode:
        return None
    tcps = layer.timeCodesPerSecond if layer.HasTimeCodesPerSecond() else 24.0
    return (layer.startTimeCode, layer.endTimeCode, tcps)


def generate(force: bool = False) -> str | None:
    """Write env_anim.usda + env_anim.json + root_unity.usda for the active environment.
    Returns the Unity root path. An environment without animation still gets root_unity.usda
    (with an empty animation layer), so Unity always has one entry point."""
    from pxr import Sdf, Usd, UsdGeom

    stamp = _stamp()
    unity_root = cfg.STAGE_DIR / UNITY_ROOT_NAME
    if not force and _up_to_date(stamp):
        return str(unity_root)
    t0 = time.perf_counter()
    os.makedirs(cfg.STAGE_DIR, exist_ok=True)
    env = Usd.Stage.Open(cfg.ENV_USD)
    default = env.GetDefaultPrim()
    if not default:
        return None
    src_root = str(default.GetPath())
    bake = env.GetStartTimeCode() if env.HasAuthoredTimeCodeRange() else 0.0
    bake_tc = Usd.TimeCode(bake)

    layer = Sdf.Layer.CreateAnonymous(".usda")
    layer.comment = (f"Generated by Tools/agv_fleet (anim_layer.py): the environment's time-sampled "
                     f"transforms and visibility frozen at time code {bake:g} for Unity's importer. Derived data - do not edit.")
    layer.customLayerData = {"agvAnimStamp": stamp}
    xf_tracks, vis_tracks = [], []

    def rel(prim) -> str:
        return str(prim.GetPath())[len(src_root) + 1:]

    def spec_for(prim):
        return Sdf.CreatePrimInLayer(layer, Sdf.Path("/World/Environment" + str(prim.GetPath())[len(src_root):]))

    def set_default(prim_spec, attr, value):
        spec = prim_spec.attributes.get(attr.GetName())
        if spec is None:
            spec = Sdf.AttributeSpec(prim_spec, attr.GetName(), attr.GetTypeName(),
                                     Sdf.VariabilityUniform if attr.GetVariability() == Sdf.VariabilityUniform else Sdf.VariabilityVarying)
        spec.default = value

    # The importer walks stage->Traverse(), which skips everything inside instances (Factory: the car
    # body on the sledge, 353 meshes). De-instance them for Unity -- in this layer only; Isaac keeps
    # instancing -- and in this scan's session layer, so animation inside them is found too.
    env.SetEditTarget(env.GetSessionLayer())
    deinstanced = 0
    while True:
        inst = [p for p in Usd.PrimRange(default, Usd.TraverseInstanceProxies()) if p.IsInstance()]
        if not inst:
            break
        for p in inst:
            p.SetInstanceable(False)
            spec_for(p).instanceable = False
            deinstanced += 1

    with Sdf.ChangeBlock():
        for prim in Usd.PrimRange(default):
            if prim.IsA(UsdGeom.Xformable):
                xf = UsdGeom.Xformable(prim)
                ops = xf.GetOrderedXformOps()
                times = sorted({t for op in ops for t in op.GetTimeSamples()})
                if times:
                    ps = spec_for(prim)
                    for op in ops:
                        set_default(ps, op.GetAttr(), op.Get(bake_tc))
                    m = []
                    for t in times:
                        mat = xf.GetLocalTransformation(Usd.TimeCode(t))
                        m.extend(round(mat[r][c], 6) for r in range(4) for c in range(4))
                    xf_tracks.append({"path": rel(prim), "t": [round(t, 4) for t in times], "m": m})
            vis = prim.GetAttribute("visibility")
            if vis and vis.GetNumTimeSamples() > 0:
                times = vis.GetTimeSamples()
                vals = [0 if vis.Get(Usd.TimeCode(t)) == UsdGeom.Tokens.invisible else 1 for t in times]
                at_bake = vis.Get(bake_tc)
                # importer skips invisible prims: keep ones that become visible later importable
                token = UsdGeom.Tokens.inherited if any(vals) else at_bake
                set_default(spec_for(prim), vis, token)
                vis_tracks.append({"path": rel(prim), "t": [round(t, 4) for t in times], "v": vals})

    layer.Export(str(cfg.STAGE_DIR / LAYER_NAME))
    doc = {
        "stamp": stamp,
        "env": cfg.ENV,
        "tcps": env.GetTimeCodesPerSecond(),
        "start": env.GetStartTimeCode(),
        "end": env.GetEndTimeCode(),
        "bake": bake,
        "xf": xf_tracks,
        "vis": vis_tracks,
    }
    with open(cfg.STAGE_DIR / JSON_NAME, "w", encoding="utf-8", newline="\n") as f:
        # stamp first (checked by _up_to_date without parsing the whole file)
        json.dump(doc, f, separators=(", ", ": "))
    text = UNITY_ROOT_TEMPLATE.format(anim=LAYER_NAME)
    old = unity_root.read_text(encoding="utf-8") if unity_root.exists() else None
    if old != text:
        unity_root.write_text(text, encoding="utf-8", newline="\n")
    print(f"[agv_fleet] anim layer: {len(xf_tracks)} animated transforms, {len(vis_tracks)} visibility tracks, {deinstanced} de-instanced, "
          f"frozen at {bake:g} ({env.GetStartTimeCode():g}..{env.GetEndTimeCode():g} @ {env.GetTimeCodesPerSecond():g} fps) "
          f"in {time.perf_counter() - t0:.1f}s -> {LAYER_NAME}, {JSON_NAME}")
    return str(unity_root)


if __name__ == "__main__":
    # Standalone (any Python with pxr): python -m agv_fleet.anim_layer [--env factory] [--force]
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("--env", default=cfg.ENV, choices=sorted(cfg.ENVIRONMENTS))
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args()
    cfg.apply_env(a.env)
    print(generate(force=a.force))

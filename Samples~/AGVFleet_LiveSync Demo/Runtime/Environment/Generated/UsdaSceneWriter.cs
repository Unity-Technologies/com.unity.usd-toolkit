using System.Collections.Generic;
using System.Globalization;
using System.Text;
using UnityEngine;

namespace Unity.USDToolkit.Samples.AGVFleet.LiveSyncDemo
{
    /// <summary>
    /// Writes a <see cref="GeneratedFactory"/> as USDA text: one layer whose default prim is
    /// <c>/GeneratedFactory</c> (Z-up, meters), UsdPreviewSurface materials under <c>Looks</c>, a <c>Plane</c>
    /// floor and one <c>Cube</c> per other part, with <c>PhysicsCollisionAPI</c> on the floor and on every
    /// part that blocks AGVs.
    ///
    /// The USD Toolkit imports and exports whole stages but has no public API to author prims, schemas or
    /// collision APIs, so the layer is written as text, like the sample's unity_ops.usda. The output is
    /// deterministic (same input, same bytes): parts in build order, invariant number formatting.
    /// </summary>
    public static class UsdaSceneWriter
    {
        public const string RootName = "GeneratedFactory";

        private sealed class Node
        {
            public readonly string Name;
            public readonly List<Node> Children = new List<Node>();
            public readonly Dictionary<string, Node> ByName = new Dictionary<string, Node>();
            public BoxPart? Part;
            public Node(string name) => Name = name;

            public Node Child(string name)
            {
                if (!ByName.TryGetValue(name, out Node n))
                {
                    n = new Node(name);
                    ByName[name] = n;
                    Children.Add(n);
                }
                return n;
            }
        }

        public static string Write(GeneratedFactory g)
        {
            var root = new Node(RootName);
            foreach (BoxPart p in g.Parts)
            {
                Node n = root;
                foreach (string seg in p.path.Split('/')) n = n.Child(seg);
                n.Part = p;
            }

            var sb = new StringBuilder(1 << 20);
            GeneratedFactoryParams q = g.Params;
            sb.Append("#usda 1.0\n(\n");
            sb.Append($"    defaultPrim = \"{RootName}\"\n");
            sb.Append("    doc = \"Generated by the USD Toolkit AGV Fleet LiveSync Demo sample (GeneratedFactoryBuilder). Regenerated on every run; do not edit.\"\n");
            sb.Append("    metersPerUnit = 1\n");
            sb.Append("    upAxis = \"Z\"\n");
            sb.Append("    customLayerData = {\n");
            sb.Append($"        string \"agvFleet:generator\" = \"{Esc(q.ToString())}\"\n");
            sb.Append($"        int \"agvFleet:seed\" = {q.seed}\n");
            sb.Append("    }\n)\n\n");

            sb.Append($"def Xform \"{RootName}\" (\n    kind = \"assembly\"\n)\n{{\n");
            sb.Append("    def Scope \"Looks\"\n    {\n");
            foreach (LookDef look in g.Looks) WriteLook(sb, look);
            sb.Append("    }\n");
            foreach (Node child in root.Children) WriteNode(sb, child, 1);
            sb.Append("}\n");
            return sb.ToString();
        }

        private static void WriteLook(StringBuilder sb, LookDef m)
        {
            string path = $"/{RootName}/Looks/{m.name}";
            sb.Append($"        def Material \"{m.name}\"\n        {{\n");
            sb.Append($"            token outputs:surface.connect = <{path}/Surface.outputs:surface>\n\n");
            sb.Append("            def Shader \"Surface\"\n            {\n");
            sb.Append("                uniform token info:id = \"UsdPreviewSurface\"\n");
            sb.Append($"                color3f inputs:diffuseColor = {V(m.color)}\n");
            if (m.emissive.maxColorComponent > 0f) sb.Append($"                color3f inputs:emissiveColor = {V(m.emissive)}\n");
            sb.Append($"                float inputs:metallic = {F(m.metallic)}\n");
            sb.Append($"                float inputs:roughness = {F(m.roughness)}\n");
            sb.Append("                token outputs:surface\n");
            sb.Append("            }\n        }\n");
        }

        private static void WriteNode(StringBuilder sb, Node n, int depth)
        {
            string ind = new string(' ', depth * 4);
            if (n.Part.HasValue && n.Children.Count == 0)
            {
                WriteCube(sb, n.Name, n.Part.Value, ind);
                return;
            }
            sb.Append($"{ind}def Xform \"{n.Name}\"\n{ind}{{\n");
            if (n.Part.HasValue) WriteCube(sb, "Shape", n.Part.Value, ind + "    ");
            foreach (Node c in n.Children) WriteNode(sb, c, depth + 1);
            sb.Append($"{ind}}}\n");
        }

        private static void WriteCube(StringBuilder sb, string name, BoxPart p, string ind)
        {
            if (p.shape == PartShape.Plane)
            {
                WritePlane(sb, name, p, ind);
                return;
            }
            string schemas = p.collision ? "\"MaterialBindingAPI\", \"PhysicsCollisionAPI\"" : "\"MaterialBindingAPI\"";
            sb.Append($"{ind}def Cube \"{name}\" (\n{ind}    prepend apiSchemas = [{schemas}]\n{ind})\n{ind}{{\n");
            sb.Append($"{ind}    double size = 1\n");
            sb.Append($"{ind}    float3[] extent = [(-0.5, -0.5, -0.5), (0.5, 0.5, 0.5)]\n");
            sb.Append($"{ind}    rel material:binding = </{RootName}/Looks/{p.look}>\n");
            if (!p.visible) sb.Append($"{ind}    token visibility = \"invisible\"\n");
            sb.Append($"{ind}    double3 xformOp:translate = {V(p.center)}\n");
            sb.Append($"{ind}    float xformOp:rotateZ = {F(p.yawDeg)}\n");
            sb.Append($"{ind}    float3 xformOp:scale = {V(p.size)}\n");
            sb.Append($"{ind}    uniform token[] xformOpOrder = [\"xformOp:translate\", \"xformOp:rotateZ\", \"xformOp:scale\"]\n");
            sb.Append($"{ind}}}\n");
        }

        private static void WritePlane(StringBuilder sb, string name, BoxPart p, string ind)
        {
            string schemas = p.collision ? "\"MaterialBindingAPI\", \"PhysicsCollisionAPI\"" : "\"MaterialBindingAPI\"";
            float hx = p.size.x * 0.5f, hy = p.size.y * 0.5f;
            sb.Append($"{ind}def Plane \"{name}\" (\n{ind}    prepend apiSchemas = [{schemas}]\n{ind})\n{ind}{{\n");
            sb.Append($"{ind}    uniform token axis = \"Z\"\n");
            sb.Append($"{ind}    double width = {F(p.size.x)}\n");
            sb.Append($"{ind}    double length = {F(p.size.y)}\n");
            sb.Append($"{ind}    float3[] extent = [({F(-hx)}, {F(-hy)}, 0), ({F(hx)}, {F(hy)}, 0)]\n");
            sb.Append($"{ind}    rel material:binding = </{RootName}/Looks/{p.look}>\n");
            sb.Append($"{ind}    double3 xformOp:translate = {V(p.center)}\n");
            sb.Append($"{ind}    uniform token[] xformOpOrder = [\"xformOp:translate\"]\n");
            sb.Append($"{ind}}}\n");
        }

        private static string F(float v) => v.ToString("0.#####", CultureInfo.InvariantCulture);
        private static string V(Vector3 v) => $"({F(v.x)}, {F(v.y)}, {F(v.z)})";
        private static string V(Color c) => $"({F(c.r)}, {F(c.g)}, {F(c.b)})";
        private static string Esc(string s) => s.Replace("\\", "\\\\").Replace("\"", "\\\"");
    }
}
